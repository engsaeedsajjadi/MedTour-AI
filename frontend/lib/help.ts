const KEY='medtour_help';
export function helpEnabled():boolean{
 if(typeof window==='undefined')return false;
 try{const v=localStorage.getItem(KEY);return v===null?true:v==='on';}catch{return true;}
}
export function setHelpEnabled(on:boolean){
 try{localStorage.setItem(KEY,on?'on':'off');}catch{}
 if(typeof window!=='undefined')window.dispatchEvent(new Event('medtour-help'));
}
